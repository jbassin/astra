// Keeps the bench page in step with the module. `bench/arm-shader-bench.html` is one
// self-contained file, so it cannot import `src/`; instead this script transpiles the module's
// own sources (shaders, the smear buffer, the solver, the strip, the flag parser and the shatter
// look) and writes them between two marker comments in the page. The page's boss demo then runs
// the same code Foundry does. `benchSync.test.ts` fails when the page is out of date.
//
//   pnpm --filter @astra/portal-arms sync-bench

import { readFileSync, writeFileSync } from "node:fs";

import ts from "typescript";

/** The sources the bench embeds, dependencies first. */
export const BENCH_MODULES = [
  "solve",
  "region",
  "strip",
  "config",
  "look",
  "ink-image",
  "shaders",
  "smear",
] as const;

export const BEGIN = "<!-- BEGIN generated by src/benchSync.ts (pnpm sync-bench); do not edit -->";
export const END = "<!-- END generated -->";

const SRC = new URL("./", import.meta.url);
export const BENCH_FILE = new URL("../bench/arm-shader-bench.html", import.meta.url);

function transpile(name: string): string {
  const source = readFileSync(new URL(`${name}.ts`, SRC), "utf8");
  return ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
      removeComments: false,
    },
  }).outputText;
}

/** The generated block, markers included: one script that defines `ArmsLib`. */
export function generate(): string {
  const factories = BENCH_MODULES.map(
    (name) => `  factories["./${name}"] = function (exports, require) {\n${transpile(name)}\n  };`,
  )
    .join("\n")
    // A closing script tag inside the code would end the block early.
    .replaceAll("</script", "<\\/script");
  const script = `<script>
// The module's own code, as CommonJS: ArmsLib.shaders, ArmsLib.smear and so on.
const ArmsLib = (() => {
  const factories = {};
  const cache = {};
  function req(name) {
    if (!cache[name]) {
      const exports = {};
      cache[name] = exports;
      factories[name](exports, req);
    }
    return cache[name];
  }
${factories}
  const lib = {};
  for (const name of ${JSON.stringify(BENCH_MODULES)}) lib[name] = req("./" + name);
  return lib;
})();
</script>`;
  return `${BEGIN}\n${script}\n${END}`;
}

/** `html` with the generated block replaced by `block`. */
export function replaceBlock(html: string, block: string): string {
  const start = html.indexOf(BEGIN);
  const end = html.indexOf(END);
  if (start < 0 || end < start) throw new Error("the bench page has no generated block");
  return html.slice(0, start) + block + html.slice(end + END.length);
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  const html = readFileSync(BENCH_FILE, "utf8");
  writeFileSync(BENCH_FILE, replaceBlock(html, generate()));
  process.stdout.write("bench page updated\n");
}

"""Generate the TS config schema (Zod) from the Pydantic models.

`generate()` returns the text of `libs/ts/config/src/config.gen.ts` (`OUTPUT`). It is one of
the generated artifacts `scripts/ontology_gen.py` owns: `just ontology-gen` writes it and
`just ontology-check` (in `just check` and CI) fails when the committed file is stale.

The input is `WholeConfig.model_json_schema()`, restricted to `TS_NAMESPACES`. Field names become
camelCase, which `decodeKdl` turns back into the same kebab-case KDL node names. The
config uses few JSON Schema shapes, and anything else fails loud:

* `string`, `integer`, `number`, `boolean`, `enum`, and an `array` of those;
* `x-astra-path` (`DataPath`, `ContentPath`): `dataPath()` / `contentPath()`, which the TS
  loader resolves against `data.root` / `data.content-root`;
* `x-astra-secret` (`Secret | None`): `secret()`, a lazy `SecretRef` or undefined.

A plaintext field must be required with no default (values live only in `config.kdl`).
`additionalProperties: false` (`extra="forbid"`) becomes `.strict()`.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .models import TS_NAMESPACES, WholeConfig

#: The generated module, relative to the repo root.
OUTPUT = Path("libs/ts/config/src/config.gen.ts")

HEADER = """\
// Generated by `just ontology-gen` from libs/py/config/src/astra_config/models.py: the Zod
// schema for the config.kdl namespaces TS reads (`TS_NAMESPACES`). Do not edit it; change
// the Pydantic models and run `just ontology-gen`. `just ontology-check` fails CI when this
// file is stale. Each field's meaning is documented in models.py.
import { z } from "zod";

import { contentPath, dataPath, secret } from "./fields";
"""

_SCALARS = {
    "string": "z.string()",
    "integer": "z.number().int()",
    "number": "z.number()",
    "boolean": "z.boolean()",
}
_PATHS = {"data": "dataPath()", "content": "contentPath()"}


class ZodGenError(ValueError):
    """The JSON Schema holds a shape the generator does not support."""


def camel(snake: str) -> str:
    """`content_root` -> `contentRoot`."""
    head, *rest = snake.split("_")
    return head + "".join(part.title() for part in rest)


def _is_secret(prop: dict[str, Any]) -> bool:
    return any(option.get("x-astra-secret") for option in prop.get("anyOf", []))


def _value(prop: dict[str, Any], where: str) -> str:
    """The Zod expression for one non-secret value schema."""
    if "x-astra-path" in prop:
        return _PATHS[prop["x-astra-path"]]
    if "enum" in prop:
        return f"z.enum({json.dumps(prop['enum'])})"
    kind = prop.get("type")
    if kind == "array":
        return f"z.array({_value(prop['items'], f'{where}[]')})"
    if isinstance(kind, str) and kind in _SCALARS:
        return _SCALARS[kind]
    raise ZodGenError(f"{where}: unsupported JSON Schema {json.dumps(prop)}")


def _field(prop: dict[str, Any], required: bool, where: str) -> str:
    if _is_secret(prop):
        if required or prop.get("default") is not None:
            raise ZodGenError(f"{where}: a secret field is `Secret | None = None`")
        return "secret()"
    if not required or "default" in prop:
        raise ZodGenError(f"{where}: a plaintext field must be required, with no default")
    return _value(prop, where)


def _namespace(const: str, schema: dict[str, Any], where: str) -> str:
    if schema.get("type") != "object":
        raise ZodGenError(f"{where}: a namespace must be an object")
    required = set(schema.get("required", []))
    lines = [f"export const {const} = z", "  .object({"]
    for name, prop in schema["properties"].items():
        expr = _field(prop, name in required, f"{where}.{name}")
        lines.append(f"    {camel(name)}: {expr},")
    lines.append("  })")
    strict = schema.get("additionalProperties") is False
    lines[-1] += "\n  .strict();" if strict else ";"
    return "\n".join(lines)


def generate() -> str:
    """The text of `config.gen.ts` for the current models."""
    schema = WholeConfig.model_json_schema()
    defs, props = schema["$defs"], schema["properties"]
    required = set(schema.get("required", []))
    blocks, members = [], []
    for ns in TS_NAMESPACES:
        if ns not in props:
            raise ZodGenError(f"TS_NAMESPACES names {ns!r}, which WholeConfig lacks")
        if ns not in required:
            raise ZodGenError(f"{ns}: a namespace must be required, with no default")
        ref = props[ns].get("$ref", "")
        model = ref.removeprefix("#/$defs/")
        if not ref.startswith("#/$defs/") or model not in defs:
            raise ZodGenError(f"{ns}: expected a $ref to a namespace model, got {props[ns]}")
        const = model.removesuffix("Config")
        blocks.append(_namespace(const, defs[model], ns))
        members.append(f"  {camel(ns)}: {const},")
    top = [
        "// Not `.strict()`: Zod's default strip drops the namespaces only Python reads.",
        "export const ConfigSchema = z.object({",
        *members,
        "});",
    ]
    return "\n\n".join([HEADER.rstrip("\n"), *blocks, "\n".join(top)]) + "\n"

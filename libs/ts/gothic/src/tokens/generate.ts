/**
 * Renders the token source (`tokens.ts`) into the files under `src/generated/`. Pure: it returns
 * each file's path (relative to the gothic package) and contents; `scripts/tokens-gen.ts` writes
 * them or, with `--check`, compares them with the committed copies.
 */
import { gothic, graphPalette, parchment, type Theme, type Token, type TokenValue } from "./tokens";

const HEADER = "Generated by `just tokens-gen` from src/tokens/tokens.ts. Do not edit.";

/** Look a colour token up by name and follow `ref`s down to a CSS literal. */
export function resolveColor(theme: Theme, value: TokenValue): string {
  let current = value;
  for (let depth = 0; depth < 8; depth++) {
    if (typeof current === "string") return current;
    const name = current.ref;
    const next = theme.colors.find((t) => t.name === name);
    if (!next) throw new Error(`token ref "${name}" names no colour in this theme`);
    current = next.value;
  }
  throw new Error("token refs nest too deeply (a cycle?)");
}

function cssValue(prefix: string, value: TokenValue): string {
  return typeof value === "string" ? value : `var(--${prefix}-${value.ref})`;
}

function declarations(prefix: string, tokens: readonly Token[]): string[] {
  return tokens.map(
    (t) => `  --${prefix}${prefix ? "-" : ""}${t.name}: ${cssValue(prefix, t.value)};`,
  );
}

function legacyAliases(prefix: string, tokens: readonly Token[]): string[] {
  return tokens
    .filter((t) => t.legacy)
    .map((t) => `  --${prefix}-${t.legacy}: var(--${prefix}-${t.name});`);
}

function themeBody(theme: Theme): string[] {
  const aliases = legacyAliases("color", theme.colors);
  return [
    ...declarations("color", theme.colors),
    "",
    ...declarations("font", theme.fonts),
    ...(theme.other.length > 0 ? ["", ...declarations("", theme.other)] : []),
    ...(aliases.length > 0
      ? [
          "",
          "  /* Old names, kept as aliases until every consumer uses the names above. */",
          ...aliases,
        ]
      : []),
  ];
}

const HEX = /^#[0-9a-f]{6}$/i;

/** camelCase a token name for a TS key: `accent-secondary` → `accentSecondary`. */
const key = (name: string): string =>
  name.replaceAll(/-([a-z])/g, (_, c: string) => c.toUpperCase());

/** The 0–1 float of one 8-bit channel, rounded to 3 places (what the GLSL uniforms use). */
const channel = (hex: string, at: number): number =>
  Math.round((Number.parseInt(hex.slice(at, at + 2), 16) / 255) * 1000) / 1000;

function paletteBlock(constName: string, themeName: string, theme: Theme): string[] {
  const opaque = theme.colors
    .map((t) => ({ key: key(t.name), hex: resolveColor(theme, t.value).toLowerCase() }))
    .filter((c) => HEX.test(c.hex));
  return [
    `/** The ${themeName} theme's opaque colours (translucent tokens are CSS-only). */`,
    `export const ${constName} = {`,
    "  /** CSS hex strings, for canvas and pixi APIs that take a string. */",
    "  hex: {",
    ...opaque.map((c) => `    ${c.key}: "${c.hex}",`),
    "  },",
    "  /** 0xRRGGBB numbers, for pixi APIs that take a number. */",
    "  pixi: {",
    ...opaque.map((c) => `    ${c.key}: 0x${c.hex.slice(1)},`),
    "  },",
    "  /** RGB 0–1 floats rounded to 3 places, for GLSL `vec3` uniforms. */",
    "  rgb: {",
    ...opaque.map(
      (c) =>
        `    ${c.key}: [${channel(c.hex, 1)}, ${channel(c.hex, 3)}, ${channel(c.hex, 5)}] as const,`,
    ),
    "  },",
    "} as const;",
  ];
}

interface GeneratedFile {
  /** Path relative to the gothic package root. */
  readonly path: string;
  readonly contents: string;
}

export function generateTokenFiles(): GeneratedFile[] {
  const gothicCss = [
    `/* ${HEADER}`,
    "   The gothic theme. Inside `@theme`, each token is both a :root custom property and a",
    "   Tailwind utility (`bg-page`, `text-accent`, `font-display`). */",
    "@theme {",
    ...themeBody(gothic),
    "}",
    "",
  ].join("\n");

  const parchmentCss = [
    `/* ${HEADER}`,
    "   The parchment theme (codex, menhir): plain custom properties, no Tailwind. */",
    ":root {",
    ...themeBody(parchment),
    "}",
    "",
  ].join("\n");

  const graphCss = [
    `/* ${HEADER}`,
    "   The akasha graph's Quartz variable names, as concrete gothic hex (canvas code can't",
    "   resolve var()). */",
    ":root {",
    ...graphPalette.map((v) => `  --${v.name}: ${resolveColor(gothic, v.value)};`),
    "}",
    "",
  ].join("\n");

  const paletteTs = [
    `// ${HEADER}`,
    "",
    ...paletteBlock("gothic", "gothic", gothic),
    "",
    ...paletteBlock("parchment", "parchment", parchment),
    "",
  ].join("\n");

  return [
    { path: "src/generated/gothic-theme.css", contents: gothicCss },
    { path: "src/generated/parchment-theme.css", contents: parchmentCss },
    { path: "src/generated/graph-palette.css", contents: graphCss },
    { path: "src/generated/palette.ts", contents: paletteTs },
  ];
}
